def fetch_s3_url(
        bucket_name:str,
        file_name:str,
        client_method='get_object'
) -> str:
    """
    Fetch a report in the S3 bucket and returns the url.
    Args:
        bucket_name: The name of the bucket.
        file_name: The type of the report.
        client_method: Type of action on the S3 bucket.

    Returns:
        url: of the signed url.
    """
    if not bucket_name or not file_name:
        print(f"error, missing bucket_name or file_name")
        return ""
    
    params={"Bucket":bucket_name,"Key":f"{file_name}.pdf"}
    signed_url=s3_presigned_url(client_method=client_method,method_params=params,expiration_time=300)
    return signed_url

def ai_task_queries_collections_update(
    user_id:str,
    task_id:str,
    tickers:list,
    report_type:str,
    collection:str,
    db_name:str,
    status:Status,
    error=None
    ) -> None:
    """
    Update the ai task query collection with
    the latest status
    Args:
        user_id: Authenticated user id.
        task_id: Generated task_id by celery.
        tickers: List of tickers.
        report_type: The type of report e.g. Rittenhouse, Overall, etc.
        collection: Name of the collection in MongoDB.
        db_name: Name of the MongoDB database.
        status: Task status.
        error: Any error message.
    """
    client = MongoClient(uri)
    print("Status of the task:")
    print(status)
    if status == Status.failed:
        print("There was an error generating the report.")
        print(f"Error: {error}")
        return None
    db = client[db_name]
    ai_task_queries_collections=db[collection]
    ai_task_queries_collections.update_one(
        {"task_id":task_id},
        {
            "$setOnInsert":{
                "user_id":user_id,
                "task_id":task_id,
                "report_type":report_type,
                "tickers":tickers,
                "timestamp":datetime.now(timezone.utc),
            },
            "$set":{
                "status":status.value
            }
            

        },
        upsert=True            
    )
    if error:
        print(f"task_id: {task_id} stored in the db as: {status.value} with error as: {error}")
        return None
    else:
        print(f"task_id: {task_id} stored in the db as: {status.value}")
        return None
    
def ai_report_collections_update(
    user_id:str,
    task_id:str,
    tickers:list,
    report_type:str,
    collection:str,
    db_name:str,
    result:list,
) -> None:
    """
    Updates the reports collection with the
    report generated by AI.

    Args:
        user_id: Authenticated user id.
        task_id: Generated task_id by celery.
        tickers: List of tickers.
        report_type: The type of report e.g. Rittenhouse, Overall, etc.
        collection: Name of the collection in MongoDB.
        db_name: Name of the MongoDB database.
        result: The report generated by AI.

    """
    client = MongoClient(uri)
    print(
        f"Updating report with task id: "
        f"{task_id} with ticker: {tickers}"
    )
    db = client[db_name]
    ai_report_collections = db[collection]
    ai_report_collections.update_one(
            {"task_id":task_id},
        {
            "$set":{
                "assistant":result,
                "report_type":report_type,
                "tickers":tickers,
                "timestamp": datetime.now(timezone.utc)
            },
            "$setOnInsert":{
                "user_id":user_id,
                "task_id":task_id
            }
        },
        upsert=True

    )
    return None


